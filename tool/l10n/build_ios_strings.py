#!/usr/bin/env python3
"""Writes iOS's own translated texts (ios/Runner/<code>.lproj/InfoPlist.strings)
from the app's translations: the microphone permission prompt is iOS's, not
Flutter's, so iOS takes it from these files in the phone's language for the
app. Source: `iosMicrophoneUsage` in lib/core/localization/l10n/app_<code>.arb.
Run after changing that string; test/ios/info_plist_strings_test.dart checks
the files are current.

  python3 tool/l10n/build_ios_strings.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
L10N = ROOT / 'lib/core/localization/l10n'
RUNNER = ROOT / 'ios/Runner'


def quoted(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


for arb in sorted(L10N.glob('app_*.arb')):
    code = arb.stem.removeprefix('app_')
    text = json.loads(arb.read_text(encoding='utf-8'))['iosMicrophoneUsage']
    out = RUNNER / f'{code}.lproj' / 'InfoPlist.strings'
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        '/* Generated by tool/l10n/build_ios_strings.py from app_'
        f'{code}.arb. */\n'
        f'"NSMicrophoneUsageDescription" = {quoted(text)};\n',
        encoding='utf-8',
    )
    print(out.relative_to(ROOT))
