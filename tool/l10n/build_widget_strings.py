"""The home-screen widgets' names in each app language (owner, 2026-11-22),
from the app's own translations (lib/core/localization/l10n/app_<code>.arb)
— as the widget pickers of Android and the iPhone list them:

  python3 tool/l10n/build_widget_strings.py

Writes android/app/src/main/res/values[-<code>]/widget_strings.xml and
ios/TahfeezWidgets/<code>.lproj/Localizable.strings.
"""
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
L10N = ROOT / 'lib/core/localization/l10n'
RES = ROOT / 'android/app/src/main/res'
IOS = ROOT / 'ios/TahfeezWidgets'

# widget key → the ARB key of its name.
NAMES = {
    'home': 'navHome',
    'prayer': 'prayerTitle',
    'qibla': 'qiblaTitle',
    'athkar': 'athkarTitle',
    'duas': 'duasTitle',
    'habits': 'habitsTitle',
    'ayah': 'homeSectionDailyAyah',
    'reading': 'homeSectionContinueReading',
    'date': 'hijriCalendarTitle',
    'memorize': 'homeSectionMemorization',
    'khatmah': 'khatmahTitle',
    'quran': 'navQuran',
}

# The widget picker's previews' words (Android): the prayers, Home's
# memorization rows.
PREVIEW = {
    'p_fajr': 'prayerFajr', 'p_sunrise': 'prayerSunrise', 'p_dhuhr': 'prayerDhuhr',
    'p_asr': 'prayerAsr', 'p_maghrib': 'prayerMaghrib', 'p_isha': 'prayerIsha',
    'p_lesson': 'memNewLesson', 'p_recent': 'memRecent', 'p_old': 'memOld',
}

# Android's folder for each app language (Indonesian is "in" there; the
# script-tagged ones by BCP 47).
ANDROID_DIR = {'id': 'in', 'ckb': 'b+ckb', 'zh': 'b+zh+Hans'}
# The iPhone's.
IOS_DIR = {'zh': 'zh-Hans'}


def main():
    for arb in sorted(L10N.glob('app_*.arb')):
        code = arb.stem.removeprefix('app_')
        d = json.loads(arb.read_text(encoding='utf-8'))
        names = {k: d[v] for k, v in NAMES.items()}
        # The four buttons together: their names, as on Home.
        # Home's date and prayer times, without the buttons.
        names['today'] = f"{d['hijriCalendarTitle']} · {d['prayerTitle']}"
        names['shortcuts'] = ' · '.join(
            d[k] for k in ('qiblaTitle', 'athkarTitle', 'duasTitle', 'habitsTitle'))
        # The same, 3 × 1 (the picker names its size too).
        names['shortcuts_small'] = names['shortcuts'] + ' (3×1)'
        folder = RES / ('values' if code == 'en' else f'values-{ANDROID_DIR.get(code, code)}')
        folder.mkdir(parents=True, exist_ok=True)
        android = {**names, **{k: d[v] for k, v in PREVIEW.items()}}
        rows = ''.join(
            f'    <string name="widget_{k}">{escape(v).replace(chr(39), chr(92) + chr(39))}</string>\n'
            for k, v in android.items())
        (folder / 'widget_strings.xml').write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tool/l10n/build_widget_strings.py from the app\'s ARBs. -->\n'
            f'<resources>\n{rows}</resources>\n', encoding='utf-8')
        lproj = IOS / f'{IOS_DIR.get(code, code)}.lproj'
        lproj.mkdir(parents=True, exist_ok=True)
        (lproj / 'Localizable.strings').write_text(
            '/* Generated by tool/l10n/build_widget_strings.py from the app\'s ARBs. */\n' +
            ''.join(f'"widget_{k}" = {json.dumps(v, ensure_ascii=False)};\n'
                    for k, v in names.items()), encoding='utf-8')
    print('ok')


if __name__ == '__main__':
    main()
