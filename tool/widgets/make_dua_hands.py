"""The Duas icon (two cupped hands, as 🤲 — Tahfeez's own drawing,
lib/core/theme/components/dua_hands_icon.dart) for the home-screen widgets,
where the app's painter can't run: the same shapes, as polygons on the
24-unit grid.

  python3 tool/widgets/make_dua_hands.py

Writes android/app/src/main/res/drawable/ic_dua_hands.xml (a vector, tinted
by the widget), android/app/src/main/res/drawable-nodpi/
widget_preview_icon_duas.png (the picker's previews), and the polygons into
ios/TahfeezWidgets/TahfeezWidgets.swift between its "dua hands" markers.
Keep its numbers as the Dart painter's.
"""
import math
import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
VECTOR = ROOT / 'android/app/src/main/res/drawable/ic_dua_hands.xml'
PREVIEW = ROOT / 'android/app/src/main/res/drawable-nodpi/widget_preview_icon_duas.png'
SWIFT = ROOT / 'ios/TahfeezWidgets/TahfeezWidgets.swift'
PRIMARY = (0x17, 0x6B, 0x5B, 255)
STEPS = 8  # points per quarter circle


def arc(cx, cy, r, a0, a1):
    return [(cx + r * math.cos(a), cy + r * math.sin(a))
            for a in (a0 + (a1 - a0) * i / STEPS for i in range(STEPS + 1))]


def rrect(l, t, r, b, tl, tr, br, bl):
    """A rounded rectangle, clockwise from its top-left corner (y down)."""
    pi = math.pi
    return (arc(l + tl, t + tl, tl, pi, 1.5 * pi) + arc(r - tr, t + tr, tr, 1.5 * pi, 2 * pi) +
            arc(r - br, b - br, br, 0, 0.5 * pi) + arc(l + bl, b - bl, bl, 0.5 * pi, pi))


def capsule(a, b, width):
    """A stroke from a to b, [width] thick, round at both ends."""
    ang = math.atan2(b[1] - a[1], b[0] - a[0])
    r = width / 2
    return (arc(b[0], b[1], r, ang - math.pi / 2, ang + math.pi / 2) +
            arc(a[0], a[1], r, ang + math.pi / 2, ang + 1.5 * math.pi))


def hand():
    shapes = [rrect(12.4, 10.6, 20.3, 21.2, 0.7, 0.7, 4.2, 3.4)]
    for x, top in [(13.2, 7.6), (15.3, 6.0), (17.4, 5.5), (19.5, 6.6)]:
        shapes.append(capsule((x, top + 0.8), (x, 12.0), 1.6))
    shapes.append(capsule((19.6, 18.0), (22.3, 13.4), 2.3))
    return shapes


def polygons():
    """Both hands: each leaned 6° in about its heel, the left one mirrored."""
    th = math.radians(-6)
    out = []
    for mirror in (False, True):
        for shape in hand():
            pts = []
            for x, y in shape:
                x, y = x - 16.3 + 0.8, y - 21.2 + 0.2
                x, y = x * math.cos(th) - y * math.sin(th), x * math.sin(th) + y * math.cos(th)
                x, y = x + 16.3, y + 21.2
                if mirror:
                    x = 24 - x
                pts.append((round(x, 2), round(y, 2)))
            out.append(pts)
    return out


def main():
    polys = polygons()
    paths = ''.join(
        '    <path android:fillColor="#FFFFFFFF" android:pathData="M' +
        ' L'.join(f'{x},{y}' for x, y in p) + ' Z" />\n' for p in polys)
    VECTOR.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Two cupped hands (Duas): generated by tool/widgets/make_dua_hands.py\n'
        '     from the app\'s own drawing; tinted by the widget. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        '    android:viewportWidth="24" android:viewportHeight="24">\n'
        f'{paths}</vector>\n', encoding='utf-8')

    k = 3 * 24 / 24  # the previews' 3 px per dp, at 24 dp
    im = Image.new('RGBA', (72, 72), (0, 0, 0, 0))
    big = Image.new('RGBA', (288, 288), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    for p in polys:
        d.polygon([(x * 12, y * 12) for x, y in p], fill=PRIMARY)
    im = big.resize((72, 72), Image.LANCZOS)
    im.save(PREVIEW, optimize=True)

    swift = ('// BEGIN dua hands (generated by tool/widgets/make_dua_hands.py)\n'
             '/// Two cupped hands (Duas) — the app\'s own drawing, as polygons on a\n'
             '/// 24-unit grid.\n'
             'let duaHandsPolygons: [[CGPoint]] = [\n' +
             ''.join('  [' + ', '.join(f'CGPoint(x: {x}, y: {y})' for x, y in p) + '],\n'
                     for p in polys) +
             ']\n// END dua hands\n')
    src = SWIFT.read_text(encoding='utf-8')
    block = re.compile(r'// BEGIN dua hands.*?// END dua hands\n', re.S)
    if not block.search(src):
        raise SystemExit('no "dua hands" markers in TahfeezWidgets.swift')
    SWIFT.write_text(block.sub(lambda _: swift, src), encoding='utf-8')
    print(len(polys), 'polygons,', sum(len(p) for p in polys), 'points')


if __name__ == '__main__':
    main()
