import 'package:freezed_annotation/freezed_annotation.dart';

part 'quranapp_special_font_models.freezed.dart';

/// The verified `quran_common.ttf` font (vendored from a local
/// AlfaazPlus/QuranApp checkout, `docs/QURAN_DATA_PROVENANCE.md` §12/§13) —
/// used for two fixed, pre-verified codepoints: the decorative
/// Surah-header title frame (U+E000) and the decorative Bismillah glyph
/// (U+FDFD). Both codepoints are confirmed present in the font's own
/// `cmap` at generation time (`tool/quran_data/src/quranapp_font_package.dart`)
/// — never assumed.
@freezed
abstract class QuranCommonFontManifest with _$QuranCommonFontManifest {
  const factory QuranCommonFontManifest({
    required int schemaVersion,
    required String assetPath,
    required String fontFamily,
    required String fontSource,
    required String fontHash,
    required DateTime generatedAt,
  }) = _QuranCommonFontManifest;
}

/// One Surah's verified `suracon.ttf` glyph, generated by
/// `tool/quran_data/src/quranapp_font_package.dart` and checked against the
/// font's real `cmap` table — never hand-written or guessed.
@freezed
abstract class SuraconGlyphEntry with _$SuraconGlyphEntry {
  const factory SuraconGlyphEntry({
    required int surahNumber,

    /// The exact single-codepoint input string that renders this Surah's
    /// calligraphic name glyph in `suracon.ttf`.
    required String inputText,
  }) = _SuraconGlyphEntry;
}

/// The full 114-surah `suracon.ttf` glyph mapping, plus the shared prefix
/// glyph QuranApp's own reference composition overlays alongside every
/// Surah name (`utils/quran/QuranGlyphs.kt`'s `Chapter.getPrefix()`).
@freezed
abstract class SuraconGlyphManifest with _$SuraconGlyphManifest {
  const factory SuraconGlyphManifest({
    required int schemaVersion,
    required String assetPath,
    required String fontFamily,
    required String fontSource,
    required String fontHash,
    required String prefixInputText,
    required DateTime generatedAt,
    required List<SuraconGlyphEntry> entries,
  }) = _SuraconGlyphManifest;
}
